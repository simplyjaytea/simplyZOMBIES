def wheel(band, cx, ground, radius=14):
    tyre = col(TYRE)
    hub = col("8D8F8C")
    for dx in range(-radius, radius + 1):
        for dy in range(-radius, radius + 1):
            d2 = dx * dx + dy * dy
            if d2 <= radius * radius:
                y = ground - radius + dy
                if d2 >= (radius - 5) ** 2:
                    band.set(cx + dx, y, tyre)
                elif d2 >= (radius - 7) ** 2:
                    band.set(cx + dx, y, hub * 0.7)
                else:
                    band.set(cx + dx, y, hub)
    band.rect(cx - 1, ground - radius - 1, 3, 3, hub * 0.6)


