#!/usr/bin/env python3
"""The first-person structure textures (docs/46, "What is a plain box today").

Every wall, window, door, low cover and fence that no kit building owns is drawn by
`godot/presentation/first_person/structure_look.gd` as the sim's own band boxes, and this script
paints what goes on them: pale concrete block with a cap course and a moss line, a poured retaining
wall, darkened cedar boards, rust-edged corrugated sheet, fitted stone, a steel yard gate, stacked
timber, rubble, a well, a tarpaulin, a kei car, a panel van, a kei truck, and wire mesh.

Nothing here is downloaded, photographed or generated by a model. Every pixel is drawn by the code
below from the colour script of docs/46, and every variation is a hash of the pixel's place, so two
runs give the same files.

The sheets hold 64 texels a metre. A band is one full-width row of a sheet: it wraps in u (256 px,
four metres) and never meets another band sideways, so nearest filtering with mipmaps cannot bleed
one material into the next along a wall. Bands are kept apart vertically by gutters that repeat
their edge rows. `structures.manifest.json` says where each band is; the view reads it and nothing
in the view names a pixel.

    python3 tools/look/build_structures.py            write the sheets and the manifest
    python3 tools/look/build_structures.py --check    rebuild in memory and compare pixels; exit 1 on a difference
    python3 tools/look/build_structures.py --preview=<dir>   also write a 4x preview of every sheet
"""

