def col(hexstr):
    return np.array([int(hexstr[i:i + 2], 16) for i in (0, 2, 4)], dtype=np.float64)


def hsh(*keys):
    x = 0x9E3779B9
    for v in keys:
        x ^= (int(v) + 0x7F4A7C15) & 0xFFFFFFFF
        x = (x * 0x85EBCA6B) & 0xFFFFFFFF
        x ^= x >> 13
        x = (x * 0xC2B2AE35) & 0xFFFFFFFF
        x ^= x >> 16
    return x


def rnd(*keys):
    return hsh(*keys) / 4294967296.0


def step(value, steps):
    """A tone held to a few steps, so a surface is a handful of flat colours and not a gradient."""
    return round(value * steps) / steps


class Band:
    """One full-width row of a sheet. x wraps; y does not."""

    def __init__(self, height, fill=None, alpha=False):
        self.h = height
        self.a = np.zeros((height, W, 3), dtype=np.float64)
        self.alpha = np.full((height, W), 255.0) if not alpha else np.zeros((height, W))
        if fill is not None:
            self.a[:, :] = fill

    def set(self, x, y, colour):
        if 0 <= y < self.h:
            self.a[y, x % W] = colour

    def get(self, x, y):
        return self.a[min(max(y, 0), self.h - 1), x % W].copy()

    def mul(self, x, y, factor):
        if 0 <= y < self.h:
            self.a[y, x % W] = self.a[y, x % W] * factor

    def blend(self, x, y, colour, amount):
        if 0 <= y < self.h:
            self.a[y, x % W] = self.a[y, x % W] * (1.0 - amount) + colour * amount

    def rect(self, x, y, w, h, colour):
        for yy in range(max(y, 0), min(y + h, self.h)):
            for xx in range(x, x + w):
                self.a[yy, xx % W] = colour

    def rect_mul(self, x, y, w, h, factor):
        for yy in range(max(y, 0), min(y + h, self.h)):
            for xx in range(x, x + w):
                self.a[yy, xx % W] = self.a[yy, xx % W] * factor

    def hline(self, y, colour, x0=0, x1=W):
        self.rect(x0, y, x1 - x0, 1, colour)

    def vline(self, x, colour, y0=0, y1=None):
        self.rect(x, y0, 1, (self.h if y1 is None else y1) - y0, colour)


def wave(x, seed, a=3, b=7):
    """A slow wander along a wall that closes at the period."""
    p1 = rnd(seed, 1) * math.tau
    p2 = rnd(seed, 2) * math.tau
    return 0.5 + 0.30 * math.sin(math.tau * a * x / W + p1) + 0.20 * math.sin(math.tau * b * x / W + p2)


def moss_line(band, ground, seed, low, high, climbs=3, climb_px=22):
    """Moss along the foot of a wall: an uneven line, darker at the ground, with a few climbs."""
    moss = col(MOSS)
    dark = col(MOSS_DARK)
    for x in range(W):
        t = min(max(wave(x, seed), 0.0), 1.0)
        height = int(round(low + (high - low) * t + (rnd(seed, x, 5) - 0.5) * 1.6))
        for y in range(height):
            yy = ground - 1 - y
            if y == height - 1 and rnd(seed, x, y, 9) < 0.45:
                continue
            band.set(x, yy, dark if y < height * 0.45 else moss)
    for k in range(climbs):
        cx = int(rnd(seed, k, 21) * W)
        reach = int(climb_px * (0.5 + 0.5 * rnd(seed, k, 22)))
        half = 3 + int(rnd(seed, k, 23) * 4)
        for dy in range(reach):
            width = max(1, int(half * (1.0 - dy / reach)))
            for dx in range(-width, width + 1):
                if rnd(seed, k, dx, dy, 24) < 0.62 - 0.4 * dy / reach:
                    band.set(cx + dx, ground - 1 - dy, moss if rnd(seed, k, dx, dy, 25) < 0.6 else dark)


def damp_foot(band, ground, rows, strength):
    """The foot of a wall is darker where the ground keeps it wet."""
    for y in range(rows):
        f = 1.0 - strength * (1.0 - y / rows)
        f = 1.0 - step(1.0 - f, 24)
        band.rect_mul(0, ground - 1 - y, W, 1, f)


def drips(band, top, seed, count, max_len, strength=0.08):
    """Rain marks under a cap: a few narrow streaks, each fading down."""
    for k in range(count):
        x = int(rnd(seed, k, 31) * W)
        length = int(8 + rnd(seed, k, 32) * (max_len - 8))
        wide = 1 + int(rnd(seed, k, 33) * 2)
        for dy in range(length):
            f = 1.0 - strength * (1.0 - dy / length)
            for dx in range(wide):
                band.mul(x + dx, top + dy, f)


def pores(band, seed, y0, y1, share, factor):
    for y in range(y0, y1):
        for x in range(W):
            if rnd(seed, x, y, 41) < share:
                band.mul(x, y, factor)


# --- concrete block ------------------------------------------------------------------------------

def cap_rows(band, y, rows, seed):
    cap = col(BLOCK_CAP)
    band.rect(0, y, W, rows, cap)
    band.hline(y, cap * 1.04)
    band.hline(y + rows - 1, col("6E6C66"))
    band.hline(y + rows - 2, cap * 0.95)
    for x in range(20, W, 64):
        band.vline(x, cap * 0.86, y + 1, y + rows - 1)


def block_courses(band, y0, courses, seed):
    base = col(BLOCK)
    mortar = col(BLOCK_MORTAR)
    band.rect(0, y0, W, courses * 12, mortar)
    for c in range(courses):
        off = 16 if c % 2 else 0
        for i in range(8):
            bx = off + i * 32
            tone = 0.955 + 0.09 * step(rnd(seed, c, i, 1), 4)
            if rnd(seed, c, i, 2) < 0.07:
                tone *= 0.93
            colour = base * tone
            by = y0 + c * 12
            band.rect(bx, by, 31, 11, colour)
            band.rect(bx, by, 31, 1, colour * 1.045)
            band.rect(bx, by + 10, 31, 1, colour * 0.95)
            band.rect(bx + 30, by, 1, 11, colour * 0.97)
            if rnd(seed, c, i, 3) < 0.09:
                cx = bx if rnd(seed, c, i, 4) < 0.5 else bx + 29
                cy = by if rnd(seed, c, i, 5) < 0.5 else by + 9
                band.rect(cx, cy, 2, 2, mortar * 0.94)


def block_side():
    band = Band(WALL_PX, col(BLOCK_MORTAR))
    cap_rows(band, 0, 7, 11)
    block_courses(band, 7, 13, 11)
    ground = WALL_PX - 1
    pores(band, 11, 7, ground, 0.012, 0.94)
    drips(band, 7, 11, 9, 46)
    damp_foot(band, ground, 26, 0.13)
    moss_line(band, ground, 11, 2, 8)
    band.hline(ground, col(SOIL))
    return band


