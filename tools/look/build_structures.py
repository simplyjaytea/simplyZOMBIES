def concrete_top(seed=14):
    """The top of a cap or a sill: cast concrete, a joint every half metre, a little lichen."""
    band = Band(TOP_PX, col(BLOCK_CAP) * 1.01)
    edge = col(BLOCK_CAP) * 0.93
    band.hline(0, edge)
    band.hline(TOP_PX - 1, edge)
    for x in range(20, W, 32):
        band.vline(x, col(BLOCK_CAP) * 0.9, 1, TOP_PX - 1)
    pores(band, seed, 1, TOP_PX - 1, 0.012, 0.94)
    for k in range(26):
        x = int(rnd(seed, k, 51) * W)
        y = 2 + int(rnd(seed, k, 52) * (TOP_PX - 5))
        band.set(x, y, col(MOSS))
        if rnd(seed, k, 53) < 0.5:
            band.set(x + 1, y, col(MOSS_DARK))
    return band


# --- poured retaining wall -----------------------------------------------------------------------

def retaining_side():
    base = col(CONCRETE)
    band = Band(WALL_PX, base)
    seed = 21
    # The marks of the formwork boards, a tone apart, and a joint every two metres.
    for y in range(6, WALL_PX - 1, 11):
        band.hline(y, base * 0.965)
    for panel in range(0, W, 128):
        tone = 0.975 + 0.05 * step(rnd(seed, panel, 1), 2)
        band.rect_mul(panel + 1, 6, 127, WALL_PX - 7, tone)
        band.vline(panel, base * 0.74, 6, WALL_PX - 1)
        band.vline(panel + 1, base * 1.04, 6, WALL_PX - 1)
    # The coping.
    cope = base * 1.09
    band.rect(0, 0, W, 6, cope)
    band.hline(0, cope * 1.03)
    band.hline(5, base * 0.72)
    # Form ties.
    for x in range(32, W, 64):
        for y in (38, 86, 134):
            band.rect(x, y, 2, 2, base * 0.8)
    pores(band, seed, 6, WALL_PX - 1, 0.014, 0.93)
    drips(band, 6, seed, 14, 70, 0.10)
    # Weep holes half a metre up, each with the stain it has made.
    ground = WALL_PX - 1
    for x in range(64, W, 128):
        y = ground - 34
        for dy in range(2, 32):
            wide = 3 if dy < 20 else 5
            for dx in range(wide):
                xx = x + dx - (wide - 3) // 2
                band.mul(xx, y + dy, 0.86)
                if rnd(seed, xx, dy, 61) < 0.35:
                    band.blend(xx, y + dy, col(MOSS_DARK), 0.6)
        band.rect(x - 1, y - 1, 5, 5, base * 1.08)
        band.rect(x, y, 3, 3, col("2E2D2A"))
    damp_foot(band, ground, 34, 0.16)
    moss_line(band, ground, seed, 3, 13, climbs=5, climb_px=30)
    band.hline(ground, col(SOIL))
    return band


# --- darkened cedar boards -----------------------------------------------------------------------

def cedar_side():
    base = col(CEDAR)
    gap = col(CEDAR_GAP)
    band = Band(WALL_PX, base)
    seed = 31
    ground = WALL_PX - 1
    for i in range(W // 8):
        bx = i * 8
        tone = 0.90 + 0.22 * step(rnd(seed, i, 1), 4)
        colour = base * tone
        band.rect(bx, 0, 7, WALL_PX, colour)
        band.rect(bx, 0, 1, WALL_PX, colour * 1.06)
        band.rect(bx + 7, 0, 1, WALL_PX, gap)
        # Grain: one or two long streaks a board.
        for g in range(2):
            gx = bx + 1 + int(rnd(seed, i, g, 2) * 5)
            gy = int(rnd(seed, i, g, 3) * (WALL_PX - 40))
            for dy in range(24 + int(rnd(seed, i, g, 4) * 60)):
                band.mul(gx, gy + dy, 0.9 if g == 0 else 1.1)
        if rnd(seed, i, 5) < 0.3:
            ky = 20 + int(rnd(seed, i, 6) * (WALL_PX - 50))
            band.rect(bx + 2, ky, 2, 2, gap * 1.3)
        # Board ends are not level at the foot.
        cut = int(rnd(seed, i, 7) * 3)
        band.rect(bx, ground - cut, 8, cut + 1, gap)
    # Weather: the foot silvers where rain splashes, then goes dark and green at the ground.
    silver = col(CEDAR_SILVER)
    for x in range(W):
        reach = int(14 + 12 * wave(x, seed, 2, 5))
        for y in range(reach):
            yy = ground - 3 - y
            if (x % 8) == 7:
                continue
            share = 0.55 * (1.0 - y / reach)
            if rnd(seed, x, y, 8) < share:
                band.blend(x, yy, silver, 0.55)
    # Two rails nailed across, as on a board fence.
    for rail_y in (26, 118):
        rail = base * 0.86
        band.rect(0, rail_y, W, 5, rail)
        band.hline(rail_y, rail * 1.12)
        band.hline(rail_y + 5, gap)
        for x in range(3, W, 8):
            band.set(x, rail_y + 2, col("8A8780"))
    top = base * 0.8
    band.rect(0, 0, W, 4, top)
    band.hline(0, top * 1.15)
    band.hline(4, gap)
    damp_foot(band, ground, 10, 0.25)
    moss_line(band, ground, seed, 0, 4, climbs=2, climb_px=10)
    band.hline(ground, col(SOIL))
    return band


