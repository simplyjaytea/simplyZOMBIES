def body_top(length, seed, kind):
    """The vehicle from above: its length along u, its two metres down the band. Front at u = 0."""
    body = col(BODY)
    glass = col(GLASS)
    band = Band(128, col("26282A"))
    band.rect(0, 0, length, 128, body)
    band.rect(0, 0, length, 2, body * 0.86)
    band.rect(0, 126, length, 2, body * 0.86)
    band.rect(0, 0, 2, 128, body * 0.86)
    band.rect(length - 2, 0, 2, 128, body * 0.86)

    def screen(x0, x1):
        band.rect(x0, 10, x1 - x0, 108, glass)
        for i in range(0, 26):
            band.set(x0 + 2 + i // 3, 16 + i, glass * 1.5)

    if kind == "car":
        band.rect(4, 6, 40, 116, body * 0.97)
        band.rect(44, 6, 1, 116, body * 0.8)
        screen(46, 70)
        band.rect(72, 8, 76, 112, body * 1.02)
        for y in (8, 119):
            band.rect(72, y, 76, 1, body * 0.84)
        screen(150, 170)
        band.rect(172, 6, 1, 116, body * 0.8)
    elif kind == "van":
        band.rect(4, 6, 18, 116, body * 0.97)
        screen(24, 44)
        band.rect(46, 8, 204, 112, body * 1.02)
        for x in range(60, 244, 22):
            band.rect(x, 12, 2, 104, body * 0.9)
            band.rect(x + 2, 12, 1, 104, body * 1.04)
        band.rect(46, 8, 204, 1, body * 0.84)
        band.rect(46, 119, 204, 1, body * 0.84)
    else:
        band.rect(4, 6, 16, 116, body * 0.97)
        screen(22, 40)
        band.rect(42, 8, 38, 112, body * 1.02)
        band.rect(80, 0, 2, 128, col("26282A"))
        # The bed: its floor of ribbed steel inside the drop sides.
        floor = col("5E625F")
        band.rect(82, 0, length - 82, 128, body * 0.9)
        band.rect(86, 4, length - 90, 120, floor)
        for y in range(8, 122, 8):
            band.rect(86, y, length - 90, 1, floor * 0.8)
            band.rect(86, y + 1, length - 90, 1, floor * 1.1)
        rust = col(RUST)
        for x in range(86, length - 4):
            for y in range(4, 124):
                if rnd(seed, x, y, 1) < 0.03:
                    band.set(x, y, rust)
    # Dust and fallen needles: a vehicle that has stood a while.
    dust = col("8E8A78")
    for x in range(length):
        for y in range(128):
            if rnd(seed, x, y, 2) < 0.035:
                band.blend(x, y, dust, 0.55)
    band.rect(length, 0, W - length, 128, col("26282A"))
    return band


