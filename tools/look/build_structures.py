# --- the yard's steel gate -----------------------------------------------------------------------

def gate_side():
    paint = col(GATE)
    dark = col(GATE_DARK)
    band = Band(WALL_PX, paint)
    seed = 71
    ground = WALL_PX - 1
    for leaf in range(0, W, 64):
        # Ribbed infill.
        for x in range(leaf, leaf + 64):
            r = (x - leaf) % 8
            band.rect(x, 0, 1, WALL_PX, paint * (1.07 if r == 0 else (0.86 if r == 1 else 1.0)))
        # The frame: stiles, a top rail, a lock rail and a bottom rail.
        band.rect(leaf, 0, 3, WALL_PX, dark)
