def compose(bands):
    """Stack bands down a sheet with gutters; height is the next power of two."""
    rows = []
    layout = {}
    y = 0
    for name, band, top_m in bands:
        a = np.clip(np.rint(band.a), 0, 255).astype(np.uint8)
        rows.append(np.repeat(a[0:1], GUTTER, axis=0))
        y += GUTTER
        layout[name] = {"y": y, "h": band.h, "top_m": top_m}
        rows.append(a)
        y += band.h
        rows.append(np.repeat(a[-1:], GUTTER, axis=0))
        y += GUTTER
    height = 1
    while height < y:
        height *= 2
    image = np.zeros((height, W, 3), dtype=np.uint8)
    stacked = np.concatenate(rows, axis=0)
    image[: stacked.shape[0]] = stacked
    image[stacked.shape[0]:] = stacked[-1:, :, :].mean(axis=(0, 1)).astype(np.uint8)
    return image, layout, height


def build():
    files = {}
    manifest = {"density": DENSITY, "period_px": W, "sheets": {}}
    for sheet_name, bands in sheets().items():
        image, layout, height = compose(bands)
        filename = "structures_%s.png" % sheet_name
        files[filename] = image
        manifest["sheets"][sheet_name] = {"file": filename, "width": W, "height": height, "bands": layout}
    fence = fence_sheet()
    files["structures_fence.png"] = fence
    manifest["sheets"]["fence"] = {
        "file": "structures_fence.png", "width": 64, "height": 128,
        "bands": {"fence_side": {"y": 0, "h": 128, "top_m": 2.0}},
    }
    return files, manifest


def manifest_text(manifest):
    return json.dumps(manifest, indent="\t", sort_keys=True) + "\n"


def main(argv):
    check = "--check" in argv
    preview = ""
    for a in argv:
        if a.startswith("--preview="):
            preview = a[len("--preview="):]
    files, manifest = build()
    manifest_path = os.path.join(OUT, "structures.manifest.json")
    if check:
        bad = 0
        for name, image in sorted(files.items()):
            path = os.path.join(OUT, name)
            if not os.path.exists(path):
                print("STRUCTURES_FAIL %s is missing" % name)
                bad += 1
                continue
            mode = "RGBA" if image.shape[2] == 4 else "RGB"
            on_disk = np.array(Image.open(path).convert(mode))
            if on_disk.shape != image.shape or not np.array_equal(on_disk, image):
                differ = -1 if on_disk.shape != image.shape else int(np.any(on_disk != image, axis=2).sum())
                print("STRUCTURES_FAIL %s differs from the build (%d pixels)" % (name, differ))
                bad += 1
        if not os.path.exists(manifest_path) or open(manifest_path).read() != manifest_text(manifest):
            print("STRUCTURES_FAIL structures.manifest.json differs from the build")
            bad += 1
        if bad:
            return 1
        print("STRUCTURES_OK %d sheets and the manifest are what the builder paints, at %d texels a metre" % (len(files), DENSITY))
        return 0
    os.makedirs(OUT, exist_ok=True)
    for name, image in sorted(files.items()):
        Image.fromarray(image, "RGBA" if image.shape[2] == 4 else "RGB").save(os.path.join(OUT, name), optimize=False)
    with open(manifest_path, "w") as f:
        f.write(manifest_text(manifest))
    if preview:
        os.makedirs(preview, exist_ok=True)
        for name, image in sorted(files.items()):
            im = Image.fromarray(image, "RGBA" if image.shape[2] == 4 else "RGB")
            if image.shape[2] == 4:
                backdrop = Image.new("RGBA", im.size, (120, 150, 110, 255))
                backdrop.alpha_composite(im)
                im = backdrop.convert("RGB")
            im.resize((im.width * 3, im.height * 3), Image.NEAREST).save(os.path.join(preview, name))
    print("STRUCTURES_BUILT %s" % ", ".join(sorted(files.keys())))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
