def fence_sheet():
    """One metre of wire fence, two metres tall, with a post at its left edge. RGBA, 64 x 128."""
    h = 128
    w = 64
    rgba = np.zeros((h, w, 4), dtype=np.uint8)
    wire = col(WIRE)
    post = col(POST)
    for y in range(3, h - 1):
        for x in range(w):
            if (x + y) % 8 == 0:
                rgba[y, x, :3] = np.clip(wire * 1.06, 0, 255)
                rgba[y, x, 3] = 255
            elif (x - y) % 8 == 0:
                rgba[y, x, :3] = np.clip(wire * 0.86, 0, 255)
                rgba[y, x, 3] = 255
    # Top rail, bottom wire, and the post.
    rgba[0:3, :, :3] = np.clip(post * 1.05, 0, 255)
    rgba[0, :, :3] = np.clip(post * 1.25, 0, 255)
    rgba[0:3, :, 3] = 255
    rgba[h - 3, :, :3] = np.clip(wire * 0.8, 0, 255)
    rgba[h - 3, :, 3] = 255
    rgba[:, 0:4, :3] = np.clip(post, 0, 255)
    rgba[:, 0, :3] = np.clip(post * 1.25, 0, 255)
    rgba[:, 3, :3] = np.clip(post * 0.75, 0, 255)
    rgba[:, 0:4, 3] = 255
    rust = col(RUST)
    for y in range(h):
        for x in range(4):
            share = 0.5 if y > h - 14 else 0.05
            if rnd(131, x, y, 1) < share:
                rgba[y, x, :3] = rust
    for y in range(h - 16, h):
        for x in range(4, w):
            if rgba[y, x, 3] and rnd(131, x, y, 2) < 0.4:
                rgba[y, x, :3] = rust
    return rgba


